def _make_wine_df(n: int = 3, region: str = "Rioja", grape: str = "Tempranillo") -> pd.DataFrame:
    """
    Crea un DataFrame sintético con n vinos de prueba.
    Los parámetros region y grape permiten probar casos conocidos y desconocidos.

    Creates a synthetic DataFrame with n test wines.
    The region and grape parameters allow testing known and unknown cases.
    """
    return pd.DataFrame(
        {
            "winery": [f"Bodega {i}" for i in range(n)],
            "wine_name": [f"Vino {i}" for i in range(n)],
            # La lista se repite con * y se recorta con [:n] para funcionar con cualquier n
            # The list repeats with * and is sliced with [:n] to work with any n
            "year": ([2018, 2019, 2020] * n)[:n],
            "rating": ([4.3, 4.5, 4.1] * n)[:n],
            "region": [region] * n,                  # Todos los vinos de la misma región / All wines from the same region
            "price_euros": ([25.0, 50.0, 100.0] * n)[:n],
            "vine_type": ["Tinto"] * n,
            "grape_variety": [grape] * n,
            "wine_ageing": ([0, 1, 0] * n)[:n],      # Alterna joven y crianza / Alternates young and aged
            "service_temperature": ["16-18°C"] * n,
            "quality_price_ratio": ([0.17, 0.09, 0.04] * n)[:n],
            "luxury_category": ([0, 0, 1] * n)[:n],
        }
    )


def _make_artifacts(n_clusters: int = 3) -> dict:
    """
    Crea un artefacto mínimo con objetos sklearn entrenados sobre datos aleatorios.
    No usa datos reales para que los tests sean rápidos e independientes del CSV.

    Creates a minimal artifact with sklearn objects trained on random data.
    Doesn't use real data so tests are fast and independent of the CSV.
    """
    # Generador de números aleatorios con semilla fija: los tests siempre dan el mismo resultado
    # Random number generator with fixed seed: tests always give the same result
    rng = np.random.default_rng(42)

    n_features = len(NUMERIC_COLS)  # Número de columnas que espera el scaler / Number of columns the scaler expects

    # Crea 60 filas de datos sintéticos con distribución normal
    # Creates 60 rows of synthetic data with normal distribution
    X_dummy = rng.standard_normal((60, n_features))

    # Entrena los tres objetos sobre los datos sintéticos
    # Trains the three objects on the synthetic data
    scaler = StandardScaler().fit(X_dummy)                                    # Aprende media y desviación / Learns mean and std
    kmeans = KMeans(n_clusters=n_clusters, random_state=42, n_init=5).fit(X_dummy)  # Calcula centroides / Calculates centroids
    pca = PCA(n_components=2, random_state=42).fit(X_dummy)                   # Calcula componentes / Calculates components

    # Lista de nombres de columnas escaladas (igual que feature_columns en el pipeline real)
    # List of scaled column names (same as feature_columns in the real pipeline)
    feature_columns = [f"{c}_scaled" for c in NUMERIC_COLS]

    # Diccionario de Target Encoding sintético con algunas regiones y uvas conocidas
    # Synthetic Target Encoding dictionary with some known regions and grapes
    encodings = {
        "region": {
            "global_mean_price": 50.0,   # Fallback si la región no está en la tabla / Fallback if region is not in the table
            "global_mean_rating": 4.3,
            "region_stats": {
                "Rioja": {"region_mean_price": 55.0, "region_mean_rating": 4.35},
                "Penedes": {"region_mean_price": 42.0, "region_mean_rating": 4.28},
            },
        },
        "grape": {
            "global_mean_price": 50.0,
            "global_mean_rating": 4.3,
            "grape_variety_stats": {
                "Tempranillo": {
                    "grape_variety_mean_price": 48.0,
                    "grape_variety_mean_rating": 4.32,
                },
                "Garnacha": {
                    "grape_variety_mean_price": 38.0,
                    "grape_variety_mean_rating": 4.25,
                },
            },
        },
    }

    # Devuelve el diccionario con la misma estructura que el pipeline real
    # Returns the dictionary with the same structure as the real pipeline
    return {
        "scaler": scaler,
        "target_encodings": encodings,
        "kmeans": kmeans,
        "pca": pca,
        "feature_columns": feature_columns,
        "k": n_clusters,  # Número de clusters / Number of clusters
    }


