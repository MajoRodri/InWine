def test_no_refitting_during_prediction(artifacts, wine_df):
    """
    Verifica que predict_from_artifacts no re-entrena el scaler.
    Si se llamara .fit() en lugar de .transform(), la media cambiaría.

    Verifies that predict_from_artifacts doesn't retrain the scaler.
    If .fit() were called instead of .transform(), the mean would change.
    """
    # Guarda una copia de la media del scaler antes de predecir
    # Saves a copy of the scaler's mean before predicting
    mean_before = artifacts["scaler"].mean_.copy()

    predict_from_artifacts(wine_df, artifacts)  # Ejecuta la predicción / Runs the prediction

    # La media debe ser exactamente la misma después de predecir
    # The mean must be exactly the same after predicting
    np.testing.assert_array_equal(artifacts["scaler"].mean_, mean_before)


