def test_append_to_catalog_writes_correct_columns(tmp_path, artifacts, wine_df):
    """
    Verifica que append_to_catalog solo escribe las columnas que loader.py necesita,
    descartando columnas internas del pipeline (PC1, PC2, price_log...).

    Verifies that append_to_catalog only writes the columns that loader.py needs,
    discarding internal pipeline columns (PC1, PC2, price_log...).
    """
    result = predict_from_artifacts(wine_df, artifacts)

    csv_path = tmp_path / "catalog.csv"  # Archivo temporal para el test / Temporary file for the test
    n = append_to_catalog(result, csv_path)

    assert n == len(wine_df)               # Devuelve el número correcto de filas / Returns the correct number of rows

    written = pd.read_csv(csv_path)        # Lee el CSV generado / Reads the generated CSV
    assert "cluster_id" in written.columns # cluster_id debe estar / cluster_id must be there
    assert len(written) == len(wine_df)    # Mismo número de filas / Same number of rows

    # Estas columnas son internas del pipeline y NO deben aparecer en el catálogo
    # These columns are internal to the pipeline and must NOT appear in the catalog
    assert "PC1" not in written.columns
    assert "price_log" not in written.columns


def test_append_to_catalog_appends_without_overwriting(tmp_path, artifacts, wine_df):
    """
    Verifica que llamar a append_to_catalog dos veces acumula filas,
    no sobreescribe las anteriores (mode="a" en to_csv).

    Verifies that calling append_to_catalog twice accumulates rows,
    doesn't overwrite the previous ones (mode="a" in to_csv).
    """
    result = predict_from_artifacts(wine_df, artifacts)
    csv_path = tmp_path / "catalog.csv"

    append_to_catalog(result, csv_path)  # Primera escritura / First write
    append_to_catalog(result, csv_path)  # Segunda escritura, debe acumular / Second write, must accumulate

    written = pd.read_csv(csv_path)
    # El doble de filas confirma que no sobreescribió / Double rows confirms it didn't overwrite
    assert len(written) == len(wine_df) * 2
