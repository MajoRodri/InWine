def test_artifact_save_and_load(tmp_path, artifacts):
    """
    Verifica que el artefacto se puede guardar en disco y cargar sin errores,
    y que las claves del diccionario se conservan.

    Verifies that the artifact can be saved to disk and loaded without errors,
    and that the dictionary keys are preserved.
    """
    # tmp_path es una carpeta temporal que pytest crea y borra automáticamente
    # tmp_path is a temporary folder that pytest creates and deletes automatically
    path = tmp_path / "test_pipeline.joblib"

    joblib.dump(artifacts, path)   # Guarda en disco / Saves to disk
    loaded = joblib.load(path)     # Carga desde disco / Loads from disk

    assert loaded is not None                              # El objeto existe / Object exists
    assert set(loaded.keys()) == set(artifacts.keys())    # Las claves coinciden / Keys match


